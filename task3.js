// Task 3 - Asynchronous JavaScript

// 1. What is a Callback and how is it used in asynchronous operations?
// A Callback is a function passed as an argument to another function. It is executed after a particular task is completed. In asynchronous operations, callbacks are used to handle the result once the task finishes.

// 2. What is a Promise? Explain its three states.
// A Promise is an object in JavaScript that represents the eventual completion or failure of an asynchronous operation.
// It has three states:
// Pending: The operation is still in progress.
// Fulfilled: The operation is completed successfully.
// Rejected: The operation has failed due to an error.

// 3. How is Async/Await used to handle Promises?
// Async/Await is a modern way of handling Promises in JavaScript. The async keyword is used to declare an asynchronous function, and the await keyword pauses the execution until the Promise is resolved.

// 4. Mention one advantage of using Async/Await compared with traditional callbacks.
// Async/Await makes code simpler, cleaner, and easier to read. It avoids callback nesting (callback hell) and makes error handling easier using try-catch blocks.

// conclusion:
// Asynchronous JavaScript helps execute time-consuming tasks without blocking the main program. Callbacks, Promises, and Async/Await are used to handle asynchronous operations.
